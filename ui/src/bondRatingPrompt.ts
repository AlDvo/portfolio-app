/**
 * Собирает итоговый промпт: методика + задание по конкретному эмитенту.
 * Пустая методика не даёт «полуметодику» — запрос без неё бессмысленен.
 */
export function buildBondRatingPrompt(query: string): string {
  const target = query.trim();
  if (!target) {
    throw new Error('Укажите ISIN, тикер или название эмитента — иначе методика не к чему применить.');
  }
  return [
    VERSION,
    METHODOLOGY,
    '',
    'ЗАДАНИЕ',
    `Проведи оценку по методике выше для: ${target}`,
  ].join('\n');
}
